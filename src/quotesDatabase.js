export const getQuotesByTheme = (searchTerm) => {
  if (!searchTerm) return quotesDatabase;

  const term = searchTerm.toLowerCase();
  return quotesDatabase.filter(quote =>
    quote.theme.some(theme => theme.toLowerCase().includes(term)) ||
    quote.text.toLowerCase().includes(term) ||
    quote.author.toLowerCase().includes(term)
  );
};

export const getRandomQuote = (filteredQuotes = quotesDatabase) => {
  const randomIndex = Math.floor(Math.random() * filteredQuotes.length);
  return filteredQuotes[randomIndex];
};
